"""Read seed runs back from MLflow and write results/ablation_summary.{md,json}."""

import argparse
import json
from pathlib import Path

import mlflow

from agent_eval_mlflow.summary import FACTORS, aggregate, markdown_table, seed_frame
from agent_eval_mlflow.tracking import DEFAULT_EXPERIMENT, DEFAULT_TRACKING_URI


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tracking-uri", default=DEFAULT_TRACKING_URI)
    ap.add_argument("--experiment", default=DEFAULT_EXPERIMENT)
    ap.add_argument("--out-dir", default="results")
    args = ap.parse_args()
    mlflow.set_tracking_uri(args.tracking_uri)
    runs = mlflow.search_runs(experiment_names=[args.experiment],
                              filter_string="tags.level = 'seed'", max_results=50000)
    if runs.empty:
        raise SystemExit(f"no seed runs in experiment {args.experiment!r}; run run_ablation.py")
    df = seed_frame(runs)
    if df.duplicated(["retriever", "guardrail", "top_k", "seed"]).any():
        raise SystemExit("duplicate (config, seed) runs found; use a fresh experiment or tracking URI")
    seeds = sorted(df["seed"].unique().tolist())
    full = aggregate(df, list(FACTORS)).sort_values(["guardrail", "retriever", "top_k"])
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    parts = [
        "# Ablation summary",
        "",
        f"Generated by `scripts/summarize_mlflow.py` from {len(df)} MLflow seed runs "
        f"(experiment `{args.experiment}`, seeds {', '.join(map(str, seeds))}). "
        "Cells are mean ± sample std across seeds. p95_latency_ms is simulated.",
        "",
        "## All configs",
        "",
        markdown_table(full, list(FACTORS)),
    ]
    marginals = {}
    for factor in FACTORS:
        agg = aggregate(df, [factor])
        marginals[factor] = agg.to_dict(orient="records")
        parts += ["", f"## By {factor} (all runs pooled over the other two factors)", "",
                  "Std here is across all pooled seed runs, so it includes config-to-config spread.",
                  "",
                  markdown_table(agg, [factor])]
    (out / "ablation_summary.md").write_text("\n".join(parts) + "\n")
    (out / "ablation_summary.json").write_text(json.dumps(
        {"experiment": args.experiment, "seeds": seeds, "n_seed_runs": len(df),
         "configs": full.to_dict(orient="records"), "by_factor": marginals}, indent=2) + "\n")
    print(f"wrote {out / 'ablation_summary.md'} and {out / 'ablation_summary.json'} "
          f"({len(full)} configs, {len(df)} seed runs)")


if __name__ == "__main__":
    main()
